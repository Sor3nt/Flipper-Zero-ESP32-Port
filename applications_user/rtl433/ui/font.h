/* Stripe rasterizer: only 5 KB of DMA storage, no full-screen RGB allocation. */
static uint16_t pi_rgb(uint32_t rgb) {
    uint16_t c=((rgb>>8)&0xf800)|((rgb>>5)&0x07e0)|((rgb>>3)&31);
    return (uint16_t)((c<<8)|(c>>8));
}
static void pi_pixel(uint16_t* stripe,unsigned sy,int x,int y,uint16_t color) {
    if(x>=0 && x<320 && y>=(int)sy && y<(int)sy+8 && y<170)
        stripe[(y-sy)*320+x]=color;
}
static void pi_text(uint16_t* stripe,unsigned sy,int x,int y,const char* text,unsigned scale,uint16_t color) {
    if (!scale || y >= (int)sy + 8 || y + (int)(7 * scale) <= (int)sy || y >= 170)
        return;
    for(unsigned i=0;text[i];i++) {
        if (x + (int)(i * 6 * scale) >= 320) break;
        unsigned c=(unsigned char)text[i];if(c<32||c>126)c='?';
        for(unsigned gx=0;gx<5;gx++) for(unsigned gy=0;gy<7;gy++) if(pi_glyphs[c-32][gx]&(1<<gy))
            for(unsigned dy=0;dy<scale;dy++) for(unsigned dx=0;dx<scale;dx++)
                pi_pixel(stripe,sy,x+i*6*scale+gx*scale+dx,y+gy*scale+dy,color);
    }
}
