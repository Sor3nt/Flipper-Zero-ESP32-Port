"""Generate compact native coastlines from vendored public-domain Natural Earth."""
from pathlib import Path
import json,hashlib,math
R=Path(__file__).resolve().parents[1]
D=R/'tools/data/wdgwars'
raw=(D/'ne_110m_land.geojson').read_bytes()
meta=json.loads((D/'source.json').read_text(encoding='utf-8'))
assert hashlib.sha256(raw).hexdigest()==meta['sha256']
def distance(p,a,b):
 dx,dy=b[0]-a[0],b[1]-a[1]
 t=((p[0]-a[0])*dx+(p[1]-a[1])*dy)/(dx*dx+dy*dy) if dx or dy else 0
 t=max(0,min(1,t));return math.hypot(p[0]-a[0]-t*dx,p[1]-a[1]-t*dy)
def simplify(seq,tol):
 if len(seq)<=2:return seq
 d,i=max((distance(seq[i],seq[0],seq[-1]),i) for i in range(1,len(seq)-1))
 if d<=tol:return [seq[0],seq[-1]]
 return simplify(seq[:i+1],tol)[:-1]+simplify(seq[i:],tol)
def ring_simplify(ring,tol):
 ring=ring[:-1] if ring[0]==ring[-1] else ring
 split=max(range(1,len(ring)),key=lambda i:math.dist(ring[i],ring[0]))
 a=simplify(ring[:split+1],tol);b=simplify(ring[split:]+[ring[0]],tol)
 out=a[:-1]+b
 return out if len(out)>=4 else ring+[ring[0]]
points=[];rings=[]
for f in json.loads(raw)['features']:
 g=f['geometry'];polys=[g['coordinates']] if g['type']=='Polygon' else g['coordinates']
 for poly in polys:
  for hole,ring in enumerate(poly):
   tol=0.025;simple=ring_simplify(ring,tol)
   while len(simple)>256:tol*=1.35;simple=ring_simplify(ring,tol)
   seq=[(round(lat*1e6),round(lon*1e6)) for lon,lat in simple]
   assert all(-90000000<=lat<=90000000 and -180000000<=lon<=180000000 for lat,lon in seq)
   rings.append((len(points),len(seq),bool(hole)));points+=seq
assert len(points)<65536
A=R/'applications_user/wdgwars_map'
header='#pragma once\n#include "wdgwars_map_model.h"\n/* Natural Earth 1:110m land, public domain. */\ntypedef struct { uint16_t first_point, point_count; bool hole; } WdgWorldRing;\nextern const WdgMapPoint wdg_world_points[];\nextern const WdgWorldRing wdg_world_rings[];\nextern const size_t wdg_world_ring_count;\nextern const size_t wdg_world_point_count;\n'
(A/'wdgwars_map_world.h').write_text(header,encoding='utf-8')
text='/* Generated by tools/generate_wdgwars_world.py. Natural Earth public domain. */\n#include "wdgwars_map_world.h"\nconst WdgMapPoint wdg_world_points[]={\n'
text+=''.join('{%d,%d},\n'%p for p in points)+'};\nconst WdgWorldRing wdg_world_rings[]={\n'
text+=''.join('{%d,%d,%s},\n'%(first,count,'true' if hole else 'false') for first,count,hole in rings)+'};\n'
text+='const size_t wdg_world_ring_count=sizeof(wdg_world_rings)/sizeof(wdg_world_rings[0]);\nconst size_t wdg_world_point_count=sizeof(wdg_world_points)/sizeof(wdg_world_points[0]);\n'
(A/'wdgwars_map_world.c').write_text(text,encoding='utf-8')
print('Generated world:',len(rings),'rings,',len(points),'vertices;',len(points)*8+len(rings)*6,'data bytes')
