#define BOARD_PIN_LCD_DC   {g("LCD_DC")}
#define BOARD_PIN_LCD_CS   {g("LCD_CS")}
#define BOARD_PIN_LCD_RST  {g("LCD_RST")}
#define BOARD_PIN_LCD_BL   {g("LCD_BL")}
#define BOARD_LCD_H_RES 320
