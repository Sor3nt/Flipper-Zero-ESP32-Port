#!/usr/bin/env python3
"""Generate assets_icon_names.c: a name -> Icon table used by asset packs.

Asset packs (Momentum format) replace firmware icons by file name, e.g.
Icons/SubGhz/Scanning_123x52.bmx replaces I_Scanning_123x52. This script reads
every `extern const Icon I_<name>;` / `A_<name>;` from assets_icons.h and
writes a table sorted by name so the firmware can binary-search it.

The build runs it (components/assets/CMakeLists.txt) whenever assets_icons.h
or this script changes, writing the table into the build directory:
    python gen_icon_names.py <output .c>
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
header = open(os.path.join(HERE, "assets_icons.h"), encoding="utf-8").read()
symbols = re.findall(r"extern const Icon ([IA])_(\w+);", header)

names = {}
for prefix, name in symbols:
    if name in names:
        raise SystemExit(f"duplicate icon name: {name}")
    names[name] = f"{prefix}_{name}"

lines = [
    "/* Generated by gen_icon_names.py from assets_icons.h - do not edit. */",
    '#include "assets_icon_names.h"',
    '#include "assets_icons.h"',
    "",
    "const AssetIconName assets_icon_names[] = {",
]
for name in sorted(names, key=lambda n: n.encode()):
    lines.append(f'    {{"{name}", &{names[name]}}},')
lines += [
    "};",
    "",
    "const size_t assets_icon_names_count = sizeof(assets_icon_names) / sizeof(assets_icon_names[0]);",
    "",
]
if len(sys.argv) != 2:
    raise SystemExit("usage: gen_icon_names.py <output .c>")
out = sys.argv[1]
text = "\n".join(lines)
# Leave an unchanged file untouched so it is not recompiled on every configure.
if not os.path.exists(out) or open(out, encoding="utf-8").read() != text:
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
print(f"{len(names)} icons -> {out}")
